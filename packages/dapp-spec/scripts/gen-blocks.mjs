#!/usr/bin/env node
/**
 * Embed blocks/*.tsx (and the shared helper modules blocks/*.ts, e.g. pageHref.ts) as strings in
 * src/blocks.generated.ts so the code generator can copy them into exported projects. The block
 * files stay the single source: the playground renders them directly and
 * `npm run typecheck:blocks` compiles them against connect-react.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const blocksDir = fileURLToPath(new URL('../blocks/', import.meta.url));
const out = fileURLToPath(new URL('../src/blocks.generated.ts', import.meta.url));

const entries = readdirSync(blocksDir)
  .filter((f) => f.endsWith('.tsx') || (f.endsWith('.ts') && !f.endsWith('.d.ts')))
  .sort()
  .map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(blocksDir + f, 'utf8').replace(/\r\n/g, '\n'))},`);

const body = `// Generated by scripts/gen-blocks.mjs from blocks/*. Do not edit.
export const BLOCK_SOURCES: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`;
writeFileSync(out, body);
console.log(`[dapp-spec] embedded ${entries.length} block sources`);
